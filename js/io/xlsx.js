/**
 * Минимальная запись .xlsx без библиотек: ZIP без сжатия, строки прямо в ячейках,
 * формулы с готовыми значениями (Excel и LibreOffice пересчитают сами).
 *
 * sheets: [{ name, cols: [ширина в символах], rows: [[ячейка…]], freeze: строк сверху }]
 * ячейка: строка | число | null | { v, f — формула без «=», s — стиль }
 * стили: 'b' — жирный, 'h' — шапка, 'n' — 0,00, 'm' — деньги, 'mb' — деньги жирным, 't' — заголовок
 */

const STYLE = { b: 1, h: 2, n: 3, m: 4, mb: 5, t: 6, i: 7 };

const esc = (s) =>
  String(s)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    // управляющие символы XML не допускает
    // eslint-disable-next-line no-control-regex
    .replace(/[\u0000-\u0008\u000b\u000c\u000e-\u001f]/g, '');

export function colName(i) {
  let s = '';
  for (let n = i + 1; n > 0; n = Math.floor((n - 1) / 26)) s = String.fromCharCode(65 + ((n - 1) % 26)) + s;
  return s;
}

function cellXml(c, ref) {
  if (c == null || c === '') return '';
  const o = typeof c === 'object' ? c : { v: c };
  const s = o.s ? ` s="${STYLE[o.s] || 0}"` : '';
  if (o.f) {
    const v = typeof o.v === 'number' && Number.isFinite(o.v) ? `<v>${o.v}</v>` : '';
    return `<c r="${ref}"${s}><f>${esc(o.f)}</f>${v}</c>`;
  }
  if (typeof o.v === 'number' && Number.isFinite(o.v)) return `<c r="${ref}"${s}><v>${o.v}</v></c>`;
  if (o.v == null || o.v === '') return s ? `<c r="${ref}"${s}/>` : '';
  return `<c r="${ref}"${s} t="inlineStr"><is><t xml:space="preserve">${esc(o.v)}</t></is></c>`;
}

function sheetXml(sh) {
  const cols = sh.cols?.length ? `<cols>${sh.cols.map((w, i) => `<col min="${i + 1}" max="${i + 1}" width="${w}" customWidth="1"/>`).join('')}</cols>` : '';
  const pane = sh.freeze
    ? `<sheetViews><sheetView workbookViewId="0"><pane ySplit="${sh.freeze}" topLeftCell="A${sh.freeze + 1}" activePane="bottomLeft" state="frozen"/></sheetView></sheetViews>`
    : '';
  const rows = sh.rows
    .map((r, i) => {
      const cells = (r || []).map((c, j) => cellXml(c, `${colName(j)}${i + 1}`)).join('');
      return cells ? `<row r="${i + 1}">${cells}</row>` : '';
    })
    .join('');
  return `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">${pane}${cols}<sheetData>${rows}</sheetData></worksheet>`;
}


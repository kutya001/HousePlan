const list = (obj, fn = (v) => v) => Object.entries(obj).map(([k, v]) => `${k} — ${fn(v)}`).join('; ');

function catalogText() {
  const indoor = CATALOG.filter((c) => !c.outdoor);
  const outdoor = CATALOG.filter((c) => c.outdoor);
  const row = (c) => `${c.type} — ${c.name}, ${c.w}×${c.d}×${c.h} м${c.wallSnap ? ', спинкой к стене' : ''}${c.elevation ? `, на высоте ${c.elevation} м` : ''}`;
  return `Мебель и оборудование дома (furniture):\n${indoor.map(row).join('\n')}\n\nОбъекты участка (outdoor):\n${outdoor.map(row).join('\n')}`;
}

/**
 * @param opts { wishes — описание дома от пользователя, project — текущий проект (доработать), example — приложить пример }
 */
export function buildAiPrompt({ wishes = '', project = null, example = true } = {}) {
  const task = wishes.trim() || '[Опишите дом: размеры, этажность, подвал или мансарда, комнаты и их площади, санузлы, лестница, крыша, участок, мебель, пожелания по окнам и входу]';
  const parts = [];
  parts.push(`Ты — опытный архитектор-планировщик частных домов. Спроектируй дом для программы HousePlan и верни его СТРОГО в формате JSON «houseplan-ai», описанном ниже. Программа сама построит по нему 2D-план и 3D-модель: стены, окна, двери, этажи, лестницы, крышу, мебель и участок.

ЗАДАНИЕ:
${task}`);
  if (project) {
    parts.push(`ТЕКУЩИЙ ПРОЕКТ — доработай его по заданию. Сохрани всё, о чём задание не говорит (координаты, стены, комнаты), меняй только нужное и верни проект ЦЕЛИКОМ:
\`\`\`json
${JSON.stringify(toExchange(project))}
\`\`\``);
  }
  parts.push(`ЕДИНИЦЫ И КООРДИНАТЫ
- Все размеры в метрах, числа с точкой, не больше 3 знаков после точки.
- План — вид сверху. Ось x направлена вправо (восток), ось y — ВНИЗ (юг). «Вверху плана» (север) — меньшие y.
- Начало координат (0, 0) поставь в центр дома. Участок — прямоугольник вокруг дома (site.boundary), дом не ближе 3 м к границе.
- Высоты (height, sill, kneeWall) отсчитываются от пола своего этажа.

ЭТАЖИ (levels) — по порядку снизу вверх
- kind: "floor" — обычный этаж; "basement" — подвал или цокольный этаж (только в начале списка, под первым этажом); "attic" — мансарда (только последней).
- height — высота в чистоте (обычно 2.7–3.0; подвал 2.2–2.6), slab — толщина перекрытия над этажом (0.2–0.3).
- foundation (в корне) — на сколько пол первого этажа выше земли (цоколь, 0.3–0.6). Для цокольного этажа с окнами над землёй — 1.0–1.5. Отметки этажей программа считает сама; подвал уходит в землю на (height + slab − foundation).
- Мансарда: kind "attic", kneeWall — высота «колена» (от пола до начала скатов, 0.8–1.5). Её наружные стены задай как у этажа ниже (те же координаты) — программа сама поднимет их до конька и срежет скатами, получатся фронтоны. Крышу (roofs) ставь на мансарду, уклон 35–45°.
- Каждый этаж описывает СВОИ стены полностью. Наружные стены верхних этажей обычно повторяют координаты этажа ниже.

СТЕНЫ (walls)
- Стена — отрезок по ОСИ (середине толщины): from [x, y] → to [x, y]. Толщина расходится поровну в обе стороны.
- type: "exterior" — наружная (толщина 0.3–0.5, обычно 0.4), "interior" — перегородка (0.1–0.15, обычно 0.12). Высоту не указывай — она равна высоте этажа + перекрытие.
- Наружные стены образуют ЗАМКНУТЫЙ контур: конец каждой стены ТОЧНО совпадает с началом следующей (одинаковые числа), последняя приходит в начало первой.
- Перегородка начинается и заканчивается ТОЧНО на оси другой стены (Т-примыкание) или в углу. Не продлевай стены за пересечения, не дублируй и не накладывай стены друг на друга.
- id — короткие уникальные строки внутри этажа ("w1", "w2"…), на них ссылаются проёмы.

ПРОЁМЫ (openings)
- wall — id стены; offset — расстояние в метрах от точки from этой стены до ЦЕНТРА проёма.
- type: "door" (стиль: ${list(OPENING_STYLES.door)}), "window" (стиль: ${list(OPENING_STYLES.window)}), "arch" — проём без двери.
- Обычные размеры: входная дверь 1.0×2.1, межкомнатная 0.8–0.9×2.1, в санузел 0.7×2.0, гаражные ворота 2.5–3.0×2.2; окно 1.2–1.6×1.4 с sill (подоконник) 0.8–0.9, в санузле 0.6×0.6 с sill 1.5, панорамное — sill 0.1.
- Проём целиком на стене: от края проёма до конца стены и до соседнего проёма не меньше 0.15 м (по оси: offset − width/2 ≥ 0.15 + полутолщина примыкающей стены).
- flipSide: true — дверь открывается на другую сторону стены; flipHinge: true — петли с другой стороны.
- В каждую комнату — хотя бы одна дверь; в жилых комнатах и на кухне — окна; вход — в наружной стене первого этажа.

КОМНАТЫ (rooms)
- Многоугольник points по ОСЯМ стен (углы — в точках пересечения осей), обход по или против часовой — не важно. Комнаты не перекрываются.
- floor — покрытие: ${list(FLOOR_MATERIALS, (v) => v.name)}.
- Ориентиры площадей: спальня 10–16 м², гостиная 18–30, кухня 8–14, санузел 3.5–6, прихожая 4–8, коридор шириной не меньше 1.0 м.

ЛЕСТНИЦЫ (stairs) — ставятся на НИЖНЕМ этаже и ведут на следующий
- shape: ${list(STAIR_SHAPES)}. x, y — центр габарита; width — ширина, length — длина габарита; flight — ширина марша (для "L" и "U").
- Без поворота (rotation 0) подъём идёт ВВЕРХ по плану (к меньшим y): нижняя ступень у y + length/2, верхний выход у y − length/2. rotation 90 — подъём на восток, 180 — на юг, 270 — на запад.
- Размеры: прямая 1.0 × 3.6–4.2 (на высоту этажа 3 м), Г-образная 2.4 × 3.0, П-образная 2.3 × 3.0, винтовая 1.8 × 1.8. Ступени программа считает сама (подъём ≈ 0.175).
- У нижней ступени и у верхнего выхода оставь свободно не меньше 1 м. На этаже выше над лестницей программа сама вырежет проём в полу — не ставь туда стены и мебель.

КРЫШИ (roofs) — на самом верхнем этаже (или мансарде)
- type: ${list(ROOF_TYPES)}. Прямоугольник x, y (центр), w × d — НАРУЖНЫЕ размеры дома (по осям + толщина стены). Конёк идёт вдоль w; если конёк должен идти вдоль y — rotation 90 и w — размер по y.
- pitch — уклон в градусах (обычно 25–35, мансарда 35–45), overhang — свес 0.4–0.6. Г-образный дом — две крыши над крыльями.
- ПЛОСКАЯ ЭКСПЛУАТИРУЕМАЯ КРОВЛЯ (терраса на крыше, «зелёная крыша»): добавь последним этажом kind "floor" — наружные стены по контуру дома с height 1.1 (парапет), пол (rooms) по всему контуру, лестницу на этаже ниже. Выход на крышу — будка или летняя кухня из стен полной высоты (height не указывай) с дверью и своей плоской крышей (roofs с type "flat" только над будкой). Беседку, грядки, мангал, скамейки, кашпо ставь в furniture этого этажа — они останутся на крыше. Отдельную скатную крышу над таким этажом не ставь.

МЕБЕЛЬ И ОБЪЕКТЫ
- furniture — в этаже (объекты сада в furniture верхнего этажа-террасы останутся на крыше), outdoor — на земле участка. x, y — центр предмета; rotation — куда смотрит СПИНКА: 0 — спинкой к северу (к стене с меньшим y), 90 — к востоку, 180 — к югу, 270 — к западу.
- Ставь вплотную к стенам: центр на расстоянии (половина толщины стены + половина глубины предмета d) от оси стены. Не перекрывай двери, проходы и лестницы; между предметами не меньше 0.6–0.8 м прохода.
- Размеры можно не указывать — берутся из каталога; при необходимости задай w, d, h.
${catalogText()}

УЧАСТОК
- site.boundary — углы участка; fence — забор (true/false), fenceHeight — его высота.
- zones — покрытия на участке (points — многоугольник): ${list(ZONE_MATERIALS, (v) => v.name)}. Дорожка от калитки к входу, площадка под машину, терраса у дома.

ПРОВЕРЬ ПЕРЕД ОТВЕТОМ
1. Контур наружных стен каждого этажа замкнут, координаты концов совпадают точно.
2. Все перегородки упираются в оси других стен, комнаты замкнуты и не перекрываются.
3. Каждый проём помещается в свою стену (offset ± width/2 внутри длины стены) и не пересекает другие проёмы.
4. Лестница ведёт на существующий этаж, не упирается в стены и двери, над ней на верхнем этаже нет стен.
5. Предметы не стоят друг в друге (прямоугольники w×d с учётом поворота не пересекаются; стулья можно задвинуть под стол), не заходят в толщу стен, не стоят в проёмах дверей, на лестнице и над лестничным проёмом с этажа ниже; перед каждой дверью с обеих сторон свободно хотя бы 60 см.
6. Мебель этажа — внутри его комнат (иначе она «висит в воздухе»); объекты участка (outdoor) — снаружи дома и не на крыльце, отдельные постройки (гараж, баня) не заходят в дом.
7. Крыша накрывает весь верхний этаж.
Программа сама проверяет это при загрузке и покажет ошибки красным — лучше сразу ответить без них.

ФОРМАТ ОТВЕТА
- Ответь ОДНИМ блоком \`\`\`json … \`\`\` без комментариев внутри. Пояснения — коротко, после блока.
- Корень: { "format": "houseplan-ai", "version": 1, "name", "units": "m", "foundation", "site", "levels": [ … ], "outdoor": [ … ], "zones": [ … ] }.
- Этаж: { "name", "kind", "height", "slab", "kneeWall" (только мансарда), "walls", "openings", "rooms", "stairs", "furniture", "roofs" }.
- Значения по умолчанию: толщина наружной стены ${DEFAULTS.wall.exterior.thickness}, перегородки ${DEFAULTS.wall.interior.thickness}, высота этажа ${DEFAULTS.levelHeight}, перекрытие ${DEFAULTS.slab}, цоколь ${DEFAULTS.foundation}.`);
  if (example) {
    parts.push(`ПРИМЕР правильного ответа (одноэтажный дом 8×6: гостиная, спальня, санузел, двускатная крыша):
\`\`\`json
${JSON.stringify(EXAMPLE)}
\`\`\``);
  }
  return parts.join('\n\n');
}

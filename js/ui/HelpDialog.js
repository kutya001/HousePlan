/** Справка: короткая инструкция и горячие клавиши. */
import { h } from './dom.js';
import { openModal } from './feedback.js';
import { SHORTCUT_HELP } from '../app/shortcuts.js';

const STEPS = [
  ['Участок', 'Кнопка «Пресеты» → «Размер участка», или инструмент «Участок» (U) — обведите границу.'],
  ['Коробка дома', 'Инструмент «Коробка» (B): протяните прямоугольник. Сверху выберите 1–3 этажа и крышу.'],
  ['Перегородки', 'Инструмент «Стена» (W), тип «Перегородка». Концы прилипают к стенам — зелёный кружок или ромб.'],
  ['Двери и окна', 'Инструменты D и O: наведите на стену и кликните. Размеры — сверху или в свойствах.'],
  ['Комнаты', 'Инструмент «Комната» (P): клик внутри стен создаёт пол и считает площадь.'],
  ['Этажи и лестница', 'Справа «+ Этаж» копирует наружные стены. Лестница (L) вырежет проём в полу этажа выше.'],
  ['Мебель и 3D', 'Вкладка «Каталог» справа. Режим «План и 3D» (клавиша 2) — смотрите результат сразу.'],
];

export class HelpDialog {
  constructor(app) {
    this.app = app;
  }

  open() {
    const steps = h(
      'ol',
      { class: 'help-steps' },
      STEPS.map(([t, d]) => h('li', {}, h('strong', {}, t), h('span', {}, d))),
    );
    const keys = h(
      'div',
      { class: 'help-keys' },
      SHORTCUT_HELP.map(([title, rows]) =>
        h('section', {}, h('h3', {}, title), h('dl', {}, rows.flatMap(([k, d]) => [h('dt', {}, h('kbd', {}, k)), h('dd', {}, d)]))),
      ),
    );
    openModal(this.app, {
      title: 'Как пользоваться',
      wide: true,
      content: h('div', { class: 'help' }, h('section', {}, h('h3', {}, 'Дом за семь шагов'), steps), keys),
      actions: [{ label: 'Понятно', primary: true }],
    });
  }
}
